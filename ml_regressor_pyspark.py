df2 = load_dataset('mpg')
# Note: seaborn.load_dataset returns a pandas DataFrame, not a Spark DataFrame.
# To work with Spark, you would need to convert this pandas DataFrame to a Spark DataFrame.
data = spark.createDataFrame(df2)
data.show()

data.printSchema()

data.columns

data.describe().toPandas().transpose()

from pyspark.sql.functions import when,lit,count,isnan,col
data.select([count(when(isnan(c)|col(c).isNull(),c)).alias(c) for c in data.columns]).show()

data.dtypes

data = data.drop('origin', 'model_year')
data.show()

# Check for NaN values in the relevant columns
from pyspark.sql.functions import isnan, col, count

# Columns used in VectorAssembler
feature_cols = ["cylinders", "displacement", "weight", "horsepower", "acceleration"]

# Select the count of NaN values for each feature column
nan_counts = data.select([count(when(isnan(col(c)), c)).alias(c) for c in feature_cols])

nan_counts.show()

# Now modify the VectorAssembler to handle invalid values
from pyspark.ml.feature import VectorAssembler
from pyspark.ml.regression import LinearRegression
from pyspark.ml.evaluation import RegressionEvaluator

# Set handleInvalid to 'skip' to drop rows with NaN values
featureassembler = VectorAssembler(inputCols = feature_cols, outputCol = "Independent Features", handleInvalid="skip")
output = featureassembler.transform(data)
output.show()

finalized_data = output.select("Independent Features", "mpg")
finalized_data.show()

from pyspark.ml.regression import LinearRegression

# Train test split
train_data, test_data = finalized_data.randomSplit([0.75, 0.25])
Regressor = LinearRegression(featuresCol='Independent Features' , labelCol="mpg")

Regressor = Regressor.fit(train_data)

# Use the Regressor trained on the MPG data to evaluate the test_data from the MPG data
pred = Regressor.evaluate(test_data) # Changed from regressor to Regressor
pred.predictions.show()

pred.r2, pred.meanAbsoluteError, pred.meanSquaredError

