spark = SparkSession.builder.master("local[*]").appName("MyApp").getOrCreate()
print("SparkSession started successfully!")

import seaborn as sns
from seaborn import load_dataset

df1 = load_dataset('tips')
# Note: seaborn.load_dataset returns a pandas DataFrame, not a Spark DataFrame.
# To work with Spark, you would need to convert this pandas DataFrame to a Spark DataFrame.
df = spark.createDataFrame(df1)
df.show()

df.printSchema()

df.columns

# Handling Categorical Features
from pyspark.ml.feature import StringIndexer


indexer = StringIndexer(inputCol = "sex", outputCol = "sex_indexed")
df_r = indexer.fit(df).transform(df)
df_r.show()

indexer = StringIndexer(inputCols = ["smoker", "day", "time"], outputCols = ["smoker_indexed", "day_indexed", "time_indexed"])

df_r = indexer.fit(df_r).transform(df_r)

df_r.show(50)

df_r = df_r.drop("sex", "smoker", "day", "time")
df_r.show()

from pyspark.ml.feature import VectorAssembler

featureassembler = VectorAssembler(inputCols = ["total_bill", "size", "sex_indexed", "smoker_indexed", "day_indexed", "time_indexed"], outputCol = "Independent Features")
output = featureassembler.transform(df_r)
output.show()

output.select("Independent Features").show()

finalized_data = output.select("Independent Features", "total_bill")
finalized_data.show()

from pyspark.ml.regression import LinearRegression

train_data, test_data = finalized_data.randomSplit([0.75, 0.25])
regressor = LinearRegression(featuresCol = "Independent Features", labelCol = "total_bill")
regressor = regressor.fit(train_data)

regressor.coefficients

import numpy as np
np.shape(regressor.coefficients)

regressor.intercept

pred=regressor.evaluate(test_data)
pred.predictions.show()

print(pred.r2,pred.meanAbsoluteError,pred.meanSquaredError)

