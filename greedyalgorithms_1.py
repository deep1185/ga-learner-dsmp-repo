"""Problem Statement

You are given two arrays:

arr[] → arrival times of trains

dep[] → departure times of trains

Each train needs a platform from its arrival to departure.
Goal: Find the minimum number of platforms required so that no train has to wait.

Greedy Approach

This is very similar to the interval scheduling overlap problem.

Steps:

Sort both arrays arr[] and dep[] separately.

Use two pointers:

i → for next arrival

j → for next departure

Keep a counter plat_needed:

If arr[i] <= dep[j] → a train arrives before the earliest departure → need one more platform → plat_needed += 1, i += 1

Else (arr[i] > dep[j]) → one train has departed → free one platform → plat_needed -= 1, j += 1

Track the maximum platforms needed at any time.
"""

def minPlatforms(arr, dep):
    n = len(arr)
    arr.sort()
    dep.sort()    ##both arrival and departure arrays are sorted

    plat_needed = 0
    result = 0
    i, j = 0, 0    #two pointer approach

    while i < n and j < n:
        if arr[i] <= dep[j]:      # arrival first (or tie)
            plat_needed += 1
            result = max(result, plat_needed)
            i += 1
        else:
            plat_needed -= 1      #departure first
            j += 1

    return result
arr = [900, 940, 950, 1100, 1500, 1800]
dep = [910,1200,1120,1130,1900,2000]

print(minPlatforms(arr, dep))  #T(c) O(nlogn + nlogn +n +n), since two sorts and two loops running, S(c) is O(1).

##alternate solution:
def parse_time(t):
    """Accepts 'HH:MM' strings or integers like 930, returns minutes since 00:00."""
    if isinstance(t, int):
        return (t // 100) * 60 + (t % 100)
    if isinstance(t, str):
        hh, mm = map(int, t.split(":"))
        return hh * 60 + mm
    raise ValueError("Unsupported time format")

def min_platforms(arrivals, departures):
    if len(arrivals) != len(departures):
        raise ValueError("arrivals and departures must be same length")

    A = sorted(parse_time(t) for t in arrivals)
    D = sorted(parse_time(t) for t in departures)

    i = j = 0
    platforms = max_platforms = 0
    n = len(A)

    while i < n and j < n:
        if A[i] <= D[j]:          # arrival first (or tie)
            platforms += 1
            max_platforms = max(max_platforms, platforms)
            i += 1
        else:                      # departure first
            platforms -= 1
            j += 1

    return max_platforms

# Example 1 (integer times)
arr = [900, 940, 950, 1100, 1500, 1800]
dep = [910, 1200, 1120, 1130, 1900, 2000]
print(min_platforms(arr, dep))  # 3

# Example 2 (HH:MM times + ties)
arr2 = ["09:00", "09:40", "09:50", "10:00"]
dep2 = ["09:00", "09:55", "10:10", "11:00"]
print(min_platforms(arr2, dep2))  # 3 (arrivals at 09:00 & 10:00 tie with departures)

