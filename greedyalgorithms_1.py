"""Problem Statement

You are given n meetings with:

start[i] → start time of meeting i

end[i] → end time of meeting i

Only one meeting can happen in a room at a time.

A meeting can start exactly at the same time another ends.

Goal: Find the maximum number of meetings that can be scheduled in the room.

Greedy Strategy

Always pick the meeting that finishes earliest (smallest end time) → this leaves maximum space for later meetings.

Sort all meetings by their end times.

Iterate through them, and keep selecting meetings that start after (or at) the end of the last selected one.
"""

start = [1, 3, 0, 5, 8, 5]
end = [2, 4, 6, 7, 9, 9]

class Meeting:
  def __init__(self, start, end, position):
    self.start = start
    self.end = end
    self.position = position

n = len(start)
meet = [Meeting(start[i], end[i], i+1) for i in range(n)]   #to keep 0th position as 1 , we write i+1 at position
meet.sort(key=lambda x: (x.end, x.start))

result = []
count = 1    #we start count as 1 since first meet is already selected
result.append(meet[0].position)
last_time = meet[0].end

for i in range(1, n):
    if meet[i].start >= last_time:
        result.append(meet[i].position)
        count += 1
        last_time = meet[i].end

print("Maximum number of meetings:", count)
print("Scheduled meeting positions:", result)   #T(c) is O(N), also S(c) is O(N)

##altenate better code
def maxMeetings(start, end):
    n = len(start)
    meetings = sorted(zip(start, end), key=lambda x: x[1])  # sort by end time

    count = 0
    last_end = -1

    for s, e in meetings:
        if s > last_end:   # can attend this meeting
            count += 1
            last_end = e

    return count

