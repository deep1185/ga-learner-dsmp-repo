##PROBLEM: Greedy algorithm to be used for change in return of lemonade at a stall for a no of customers:
def lemonadeChange(bills):
    five, ten = 0, 0
    for bill in bills:
        if bill == 5:
            five += 1
        elif bill == 10:
            if five >= 1:
                five -= 1
                ten += 1
            else:
                return False
        else:  # bill == 20
            if ten >= 1 and five >= 1:
                ten -= 1
                five -= 1
            elif five >= 3:
                five -= 3
            else:
                return False
    return True

