"""Problem Statement

You are given:

A set of items, each with a value val[i] and a weight wt[i].

A knapsack with capacity W.

You can take fractions of items (not just whole items).

Goal: Maximize the total value in the knapsack.

Key Idea (Greedy Choice)

Compute value/weight ratio for each item.

Always pick the item with the highest ratio first.

If the entire item fits, take it fully.

Otherwise, take only the fraction that fits.
"""

##alternate solution:
class Solution:
  def __init__(self, val, wt):
    self.val = val
    self.wt = wt
    self.ratio = val/wt
  def fractional_knapsack(self, W, items):
    items.sort(key=lambda x: x.ratio, reverse=True)
    final_val = 0.0
    currW = 0.0
    for item in items:
      if currW + item.wt <= W:
        currW += item.wt
        final_val += item.val
      else:
        remain_wt = W - currW
        final_val += item.ratio * remain_wt
        break
    return final_val
#Example:
items = [Solution(60, 10), Solution(100, 20), Solution(100, 50), Solution(200, 50)]
W = 90
# Create a dummy Solution instance with valid values just to call the method
dummy_solution = Solution(1, 1)
print(f"Maximum value in Knapsack = {dummy_solution.fractional_knapsack(W, items)}")   #T(c) is O(nlogn) for sorting + O(n) for iteration, S(c) is O(1).

