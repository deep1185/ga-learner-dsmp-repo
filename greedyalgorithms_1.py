##PROBLEM: Greedy Algorithm Jump Game 2:
##You are given an array nums, where nums[i] = maximum jump length from index i.
##Start at index 0.
##Goal: Find the minimum number of jumps required to reach the last index.
##(Assume it’s always possible to reach the end.)
def jump(nums):
    jumps = 0
    left, right = 0, 0

    while right < len(nums) - 1:
        farthest = 0     # farthest we can reach
        for i in range(left, right + 1):  #left to right pointer, right included
            farthest = max(farthest, i + nums[i])   #i + nums[i] e.g. index plus value at index
        left = right + 1
        right = farthest
        jumps += 1

    return jumps
nums = [2, 3, 1, 4, 1, 1, 1, 2]
print(jump(nums))   #T(c) is O(N),since entire lust is iterated only once, S(c) is O(1), no stack used

